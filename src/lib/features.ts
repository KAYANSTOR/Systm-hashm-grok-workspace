/**
 * مفاتيح تشغيل/إيقاف الوحدات (Feature Flags) — مصدر واحد للحقيقة.
 * ---------------------------------------------------------------
 * كل وحدة موقوفة مؤقتًا تبقى **كاملة في الكود**، ويُعاد تفعيلها بإرجاع
 * القيمة إلى `true` دون أي تعديل آخر. أوقفناها بطلب صاحب المشروع لتبسيط
 * الاستخدام اليومي في المعمل إلى أن تُجهَّز الحسابات والصلاحيات فعليًا.
 *
 * الأثر التقني للوضع الموقوف:
 *  - AUTH_REQUIRED=false  → لا شاشة دخول ولا جلسة، والخادم يتعامل مع الجهاز
 *    كهوية ثابتة واحدة. ⚠️ أمنيًا: أي شخص يملك الرابط يفتح النظام كمدير،
 *    لذلك هذا وضع مؤقت مقصود ومعلوم لصاحب المعمل، لا وضع إنتاج نهائي.
 *  - ACCESS_CONTROL=false → لا شاشات موظفين/أدوار، ولا تصفية للقوائم حسب
 *    الصلاحيات (كل الشاشات ظاهرة)، والخادم لا يفرض فحص الصلاحيات.
 */
export const FEATURES = {
  /** تسجيل الدخول/الجلسات (Better Auth). */
  AUTH_REQUIRED: false,
  /** الموظفون والأدوار والصلاحيات. */
  ACCESS_CONTROL: false,
  /**
   * فواتير بيع البضاعة والمشتريات في الواجهة.
   * `false` = الواجهة مخصّصة لـ«خدمات التطريز» فقط (الشاشة والزر الرئيسي والتصفية)،
   * مع **بقاء كامل منطق الفواتير والقيود والمخزون كما هو** — لا حذف لأي شيء.
   * الفواتير القديمة (بيع/شراء) تبقى ظاهرة في القائمة وقابلة للطباعة والتعديل.
   */
  PRODUCT_SALES: false,
} as const;

/** اختصارات مقروءة تُستورد في الواجهة والخادم. */
export const AUTH_REQUIRED = FEATURES.AUTH_REQUIRED;
export const ACCESS_CONTROL = FEATURES.ACCESS_CONTROL;
export const PRODUCT_SALES = FEATURES.PRODUCT_SALES;

